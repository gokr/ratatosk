import 'package:flutter/material.dart';

/// English is the fallback for strings not translated yet.
String tr(BuildContext context, String english) =>
    Localizations.localeOf(context).languageCode == 'sv'
        ? swedish[english] ?? english
        : english;

/// Translate a template before inserting values such as names or counts.
String trp(BuildContext context, String english, List<Object?> values) {
  final translated = tr(context, english);
  return translated.replaceAllMapped(RegExp(r'\{(\d+)\}'), (match) {
    final index = int.parse(match[1]!);
    return index < values.length ? '${values[index]}' : match[0]!;
  });
}

